class days
{
  public static void main(String[] args)
   {
      String day="mon";
       switch(day)
        {
           case "mon":System.out.println("kannada");
                       break;
           case "tue":System.out.println("english");
                       break;
           case "wed":System.out.println("hindi");
                       break;
           case "thu":System.out.println("maths");
                       break;
           case "fri":System.out.println("science");
                       break;
           case "sat":System.out.println("social");
                       break;
              default:System.out.println("invalid");
       }
   }
}
                      
